# 4. واجهة التطبيق بعد تسجيل الدخول
# ==========================================
if st.session_state.authenticated:
    st.success(
        f"تم تسجيل الدخول بنجاح! مرحباً بك: {st.session_state.user_email}"
    )

    st.subheader("📋 نظام الاستفسارات والخدمات الرقمية")

    # حقل استقبال استفسار الطالب أو العضو
    user_query = st.text_area(
        "اكتب استفسارك هنا:",
        placeholder="مثال: متى يبدأ التسجيل للترم القادم؟",
    )

    if st.button("إرسال الاستفسار"):
        if user_query.strip():
            # يمكنك هنا إضافة كود حفظ الاستفسار في قاعدة بيانات أو إرساله
            st.success("تم إرسال استفسارك بنجاح! سيتم الرد عليك قريباً.")
        else:
            st.warning("رجاءً اكتب الاستفسار أولاً قبل الضغط على زر الإرسال.")

    st.divider()

    # زر تسجيل الخروج
    if st.button("تسجيل الخروج"):
        st.session_state.clear()
        st.rerun()
